"""Copy the web fonts the theme uses into theme/assets and write snippets/font-faces.liquid.
   python3 tools/fonts.py
Sources: @fontsource packages (OFL) from the book project's node_modules, @fontsource-variable/archivo, and DSEG (OFL).
Only the latin subset is shipped. Browsers download a face only when a page actually uses it."""
import os, shutil

FS = '/home/claude/gift/node_modules/@fontsource'
FSV = '/home/claude/store/tools/preview/node_modules/@fontsource-variable'
DSEG = '/home/claude/gift/node_modules/dseg/fonts'
THEME = '/home/claude/store/theme'

# css family, asset file, source path, weight, style
FONTS = [
    ('Archivo', 'f-archivo-var.woff2', f'{FSV}/archivo/files/archivo-latin-standard-normal.woff2', '100 900', 'normal', '62% 125%'),
]
STATIC = {   # family: (slug, [weights])
    'Archivo Black': ('archivo-black', [400]),
    'Knewave': ('knewave', [400]),
    'Titan One': ('titan-one', [400]),
    'VT323': ('vt323', [400]),
    'Bungee': ('bungee', [400]),
    'Press Start 2P': ('press-start-2p', [400]),
    'Courier Prime': ('courier-prime', [400, 700]),
    'Permanent Marker': ('permanent-marker', [400]),
    'Gochi Hand': ('gochi-hand', [400]),
    'Leckerli One': ('leckerli-one', [400]),
    'Libre Franklin': ('libre-franklin', [400, 700, 900]),
    'Luckiest Guy': ('luckiest-guy', [400]),
    'Special Elite': ('special-elite', [400]),
    'Comic Neue': ('comic-neue', [400, 700]),
    'Monoton': ('monoton', [400]),
    'Anton': ('anton', [400]),
    'Caveat': ('caveat', [500, 700]),
    'Kalam': ('kalam', [400, 700]),
    'Lilita One': ('lilita-one', [400]),
    'Patrick Hand': ('patrick-hand', [400]),
    'Nanum Pen Script': ('nanum-pen-script', [400]),
    'Reenie Beanie': ('reenie-beanie', [400]),
    'Rock Salt': ('rock-salt', [400]),
    'Silkscreen': ('silkscreen', [400, 700]),
    'Limelight': ('limelight', [400]),
    'Righteous': ('righteous', [400]),
}
for fam, (slug, ws) in STATIC.items():
    for w in ws:
        FONTS.append((fam, f'f-{slug}-{w}.woff2', f'{FS}/{slug}/files/{slug}-latin-{w}-normal.woff2', str(w), 'normal', None))
FONTS += [
    ('DSEG7', 'f-dseg7-bold.woff2', f'{DSEG}/DSEG7-Classic/DSEG7Classic-Bold.woff2', '700', 'normal', None),
    ('DSEG7', 'f-dseg7-regular.woff2', f'{DSEG}/DSEG7-Classic/DSEG7Classic-Regular.woff2', '400', 'normal', None),
    ('DSEG14', 'f-dseg14-bold.woff2', f'{DSEG}/DSEG14-Classic/DSEG14Classic-Bold.woff2', '700', 'normal', None),
]

out = ['{%- comment -%} Generated by tools/fonts.py. Faces download only when a page uses them. {%- endcomment -%}', '<style>']
total = 0
for fam, asset, src, w, st, stretch in FONTS:
    if not os.path.exists(src):
        raise SystemExit(f'missing {src}')
    shutil.copyfile(src, f'{THEME}/assets/{asset}')
    total += os.path.getsize(src)
    s = f"@font-face{{font-family:'{fam}';src:url({{{{ '{asset}' | asset_url }}}}) format('woff2');font-weight:{w};font-style:{st};font-display:swap;"
    if stretch:
        s += f'font-stretch:{stretch};'
    out.append(s + '}')
out.append('</style>')
open(f'{THEME}/snippets/font-faces.liquid', 'w').write('\n'.join(out) + '\n')
print(len(FONTS), 'faces,', round(total / 1024), 'KB in total (each page loads only what it uses)')
